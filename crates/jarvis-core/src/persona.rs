//! Фразы Джарвиса: приветствие, успех, ошибка, непонимание, прощание.
//!
//! Пулы — константы, выбор — случайный через `fastrand`. Позже сюда можно
//! добавить TOML/LLM, не меняя вызывающий код.

const GREETING: &[&str] = &[
    "К вашим услугам, сэр.",
    "Слушаю вас, сэр.",
    "Я здесь, сэр.",
    "Готов выполнить любую задачу, сэр.",
];

const SUCCESS: &[&str] = &[
    "Будет сделано, сэр.",
    "Выполняю, сэр.",
    "Как вы прикажете, сэр.",
    "Успешно, сэр.",
];

const ERROR: &[&str] = &[
    "К сожалению, сэр, произошла ошибка.",
    "Система дала сбой, сэр.",
    "Я не могу выполнить эту команду, сэр.",
];

const NOT_UNDERSTOOD: &[&str] = &[
    "К сожалению, сэр, я не совсем понял вас.",
    "Не могли бы вы повторить, сэр?",
    "Повторите запрос, пожалуйста.",
];

const FAREWELL: &[&str] = &[
    "До связи, сэр.",
    "Конец связи. Джарвис отключается.",
    "До завтра, сэр.",
    "Спокойной ночи, сэр.",
];

fn pick(pool: &'static [&'static str]) -> &'static str {
    pool[fastrand::usize(..pool.len())]
}

/// Приветствие при запуске.
pub fn greeting() -> &'static str {
    pick(GREETING)
}

/// Успешное выполнение: фраза + деталь.
pub fn success(detail: &str) -> String {
    format!("{} {}", pick(SUCCESS), detail)
}

/// Ошибка: фраза + деталь в скобках.
pub fn error(detail: &str) -> String {
    format!("{} ({})", pick(ERROR), detail)
}

/// Ввод не распознан.
pub fn not_understood(input: &str) -> String {
    format!("{} — «{}»", pick(NOT_UNDERSTOOD), input)
}

/// Прощание при выходе.
pub fn farewell() -> &'static str {
    pick(FAREWELL)
}
